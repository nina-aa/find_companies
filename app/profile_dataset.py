"""Profile the raw companies dataset into data/PROFILE.md.

The profiling in PLAN.md was done by hand; this script makes it reproducible and
reviewable. Run: ``python -m app.profile_dataset``.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = REPO_ROOT / "data" / "companies.json"
DEFAULT_OUTPUT = REPO_ROOT / "data" / "PROFILE.md"

# The description template observed in PLAN.md:
#   "{AI-powered|data-driven|cloud-native} {platform|engine|software} for {topics}."
_TOPIC_SPLIT = re.compile(r",| and | & |/", flags=re.IGNORECASE)


def _load(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def _fmt_counter(counter: Counter, limit: int | None = None) -> str:
    items = counter.most_common(limit)
    return "\n".join(f"| {key!r} | {count} |" for key, count in items)


def _extract_topics(description: str) -> list[str]:
    """Best-effort pull of the topic phrases after 'for ' in the template."""
    lowered = description.strip().rstrip(".")
    marker = " for "
    idx = lowered.find(marker)
    tail = lowered[idx + len(marker):] if idx != -1 else lowered
    parts = [p.strip() for p in _TOPIC_SPLIT.split(tail)]
    return [p for p in parts if p]


def build_profile(rows: list[dict]) -> str:
    n = len(rows)
    industries = Counter(r.get("industry") for r in rows)
    locations = Counter(r.get("location") for r in rows)
    revenue = Counter(r.get("revenue_range") for r in rows)
    founded = [r["founded_year"] for r in rows if isinstance(r.get("founded_year"), int)]
    employees = [r["employee_count"] for r in rows if isinstance(r.get("employee_count"), int)]
    descriptions = [r.get("description", "") for r in rows]
    distinct_desc = len(set(descriptions))

    topics = Counter()
    for desc in descriptions:
        topics.update(_extract_topics(desc))

    # Cross-check: any company with >3000 employees in the bottom revenue bucket?
    big_and_poor = [
        r for r in rows
        if isinstance(r.get("employee_count"), int)
        and r["employee_count"] > 3000
        and r.get("revenue_range") == "0-1M"
    ]
    over_5000 = [r for r in rows if isinstance(r.get("employee_count"), int) and r["employee_count"] > 5000]

    lines: list[str] = []
    lines.append("# Dataset profile — `data/companies.json`")
    lines.append("")
    lines.append(f"_Generated by `python -m app.profile_dataset`. Rows: **{n:,}**._")
    lines.append("")
    lines.append("## Field domains")
    lines.append("")
    lines.append(f"### `industry` — {len(industries)} distinct")
    lines.append("")
    lines.append("| value | count |")
    lines.append("|---|---|")
    lines.append(_fmt_counter(industries))
    lines.append("")
    lines.append(f"### `location` — {len(locations)} distinct")
    lines.append("")
    lines.append("| value | count |")
    lines.append("|---|---|")
    lines.append(_fmt_counter(locations))
    lines.append("")
    lines.append(f"### `revenue_range` — {len(revenue)} distinct")
    lines.append("")
    lines.append("| value | count |")
    lines.append("|---|---|")
    lines.append(_fmt_counter(revenue))
    lines.append("")
    lines.append("### numeric ranges")
    lines.append("")
    lines.append("| field | min | max |")
    lines.append("|---|---|---|")
    lines.append(f"| `founded_year` | {min(founded)} | {max(founded)} |")
    lines.append(f"| `employee_count` | {min(employees)} | {max(employees)} |")
    lines.append("")
    lines.append("### `description`")
    lines.append("")
    lines.append(f"- distinct descriptions: **{distinct_desc:,}** of {n:,} rows")
    lines.append(f"- top 30 topic phrases (after `for ` in the template):")
    lines.append("")
    lines.append("| topic | count |")
    lines.append("|---|---|")
    lines.append(_fmt_counter(topics, 30))
    lines.append("")
    lines.append("## Feasibility cross-checks (drive the eval expectations)")
    lines.append("")
    lines.append(f"- companies with `employee_count` > 5000: **{len(over_5000)}** "
                 f"(Q5 asks for this → must return empty)")
    lines.append(f"- companies with > 3000 employees AND `revenue_range == '0-1M'`: "
                 f"**{len(big_and_poor)}**")
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Profile the companies dataset.")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    rows = _load(args.input)
    profile = build_profile(rows)
    args.output.write_text(profile, encoding="utf-8")
    print(f"wrote {args.output} ({len(rows):,} rows profiled)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
